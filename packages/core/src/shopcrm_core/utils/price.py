"""Форматирование цен с поддержкой до 18 знаков после точки (crypto-friendly)."""
from decimal import Decimal

# Минимальное число знаков после точки в отображении цены.
_MIN_PLACES = Decimal("0.01")


def format_price(value: float | int | str | Decimal | None) -> str:
    """Форматирует цену: минимум 2 знака после точки, без потери точности.

    Обычные цены показываются с двумя знаками, а значения с большей
    точностью (crypto) — полностью, без хвостовых нулей.

    Примеры:
        10            -> "10.00"
        10.5          -> "10.50"
        10.12         -> "10.12"
        0.000004      -> "0.000004"
        10.123        -> "10.123"
        0.123456789012345678 -> "0.123456789012345678"
        None          -> "0.00"
    """
    if value is None:
        return "0.00"

    if isinstance(value, float):
        # Убираем артефакты float-арифметики: 0.30000000000000004 -> 0.3
        value = round(value, 12)

    d = Decimal(str(value))
    two_places = d.quantize(_MIN_PLACES)
    if two_places == d:
        # Значимых знаков не больше двух: показываем ровно два (10 -> "10.00")
        return format(two_places, "f")
    # Точность больше двух знаков: показываем всё, без хвостовых нулей
    return format(d.normalize(), "f")
