"""Форматирование цен с поддержкой до 18 знаков после точки (crypto-friendly)."""
from decimal import Decimal


def format_price(value: float | int | str | Decimal | None) -> str:
    """Форматирует цену: убирает хвостовые нули, не округляет до 2 знаков.

    Примеры:
        10.50       -> "10.5"
        100.0       -> "100"
        0.00000001  -> "0.00000001"
        0.123456789 -> "0.123456789"
        10.123456789012345678 -> "10.123456789012345678"
    """
    if value is None:
        return "0"

    d = Decimal(str(value))
    # Normalize убирает хвостовые нули: 10.50 -> 10.5, 100.0 -> 1E+2
    # Используем format с 'f' чтобы избежать экспоненциальной нотации
    s = format(d.normalize(), "f")
    return s
